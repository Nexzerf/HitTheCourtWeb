CREATE SCHEMA IF NOT EXISTS hitthecourt;
SET search_path TO hitthecourt;

-- อัปเดต updated_at อัตโนมัติ (แทน ON UPDATE CURRENT_TIMESTAMP ของ MySQL)
CREATE OR REPLACE FUNCTION hitthecourt.set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TABLE admins (
    admin_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    varchar(50)  NOT NULL UNIQUE,
    password    varchar(255) NOT NULL,
    email       varchar(100),
    full_name   varchar(100),
    role        varchar(20)  NOT NULL DEFAULT 'admin' CHECK (role IN ('super_admin', 'admin', 'staff')),
    status      varchar(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    last_login  timestamp(0),
    created_at  timestamp(0) NOT NULL DEFAULT now()
);

CREATE TABLE sports (
    sport_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_name       varchar(50)  NOT NULL,
    name_th          varchar(100),
    slug             varchar(50)  NOT NULL UNIQUE,
    description      text,
    duration_minutes integer      NOT NULL,
    price            integer      NOT NULL,
    max_courts       integer      DEFAULT 1,
    image            varchar(255),
    status           varchar(20)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_at       timestamp(0) NOT NULL DEFAULT now(),
    price_per_round  numeric(10,2) DEFAULT 0,
    total_courts     integer      DEFAULT 1
);

CREATE TABLE courts (
    court_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id     integer NOT NULL REFERENCES sports (sport_id) ON DELETE CASCADE,
    court_number integer NOT NULL,
    court_name   varchar(50),
    status       varchar(20) NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'maintenance', 'reserved')),
    created_at   timestamp(0) NOT NULL DEFAULT now(),
    UNIQUE (sport_id, court_number)
);

CREATE TABLE time_slots (
    slot_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id   integer NOT NULL REFERENCES sports (sport_id) ON DELETE CASCADE,
    start_time time(0) NOT NULL,
    end_time   time(0) NOT NULL,
    status     varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    UNIQUE (sport_id, start_time)
);

CREATE TABLE equipment (
    eq_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id          integer NOT NULL REFERENCES sports (sport_id) ON DELETE CASCADE,
    eq_name           varchar(100) NOT NULL,
    name_th           varchar(150),
    unit_note         varchar(255),
    unit_note_th      varchar(255),
    price             integer NOT NULL,
    stock             integer NOT NULL DEFAULT 0,
    fine_amount       integer DEFAULT 50,
    max_per_court     integer DEFAULT 10,
    member_free_units integer NOT NULL DEFAULT 0,
    status            varchar(20) NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'unavailable')),
    created_at        timestamp(0) NOT NULL DEFAULT now()
);
CREATE INDEX ON equipment (sport_id);

CREATE TABLE users (
    user_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       varchar(50)  NOT NULL UNIQUE,
    first_name     varchar(100),
    last_name      varchar(100),
    password       varchar(255) NOT NULL,
    email          varchar(100) NOT NULL UNIQUE,
    phone          varchar(20),
    is_member      smallint     DEFAULT 0,
    member_expire  date,
    points         integer      DEFAULT 0,
    total_bookings integer      DEFAULT 0,
    created_at     timestamp(0) NOT NULL DEFAULT now(),
    updated_at     timestamp(0) NOT NULL DEFAULT now()
);
-- MySQL เทียบชื่อผู้ใช้/อีเมลแบบไม่สนตัวพิมพ์เล็กใหญ่ ทำให้ Postgres ทำแบบเดียวกัน
CREATE UNIQUE INDEX users_username_lower ON users (lower(username));
CREATE UNIQUE INDEX users_email_lower ON users (lower(email));
CREATE TRIGGER users_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION hitthecourt.set_updated_at();

CREATE TABLE membership_plans (
    plan_id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_name              varchar(50) NOT NULL,
    duration_months        integer NOT NULL,
    price                  numeric(10,2) NOT NULL,
    discount_day1          integer DEFAULT 30,
    discount_day16         integer DEFAULT 30,
    discount_consecutive   integer DEFAULT 20,
    discount_first_booking integer DEFAULT 10,
    free_equipment_limit   integer DEFAULT 4,
    advance_booking_days   integer DEFAULT 7,
    features               text,
    status                 varchar(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_at             timestamp(0) NOT NULL DEFAULT now()
);

CREATE TABLE user_membership (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        integer NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    plan_id        integer NOT NULL REFERENCES membership_plans (plan_id),
    first_name     varchar(100),
    last_name      varchar(100),
    email          varchar(100),
    phone          varchar(20),
    start_date     date NOT NULL,
    end_date       date NOT NULL,
    total_price    numeric(10,2),
    payment_method varchar(20) DEFAULT 'promptpay' CHECK (payment_method IN ('promptpay', 'bank_transfer')),
    payment_status varchar(20) NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending', 'paid', 'verified')),
    slip_image     varchar(255),
    created_at     timestamp(0) NOT NULL DEFAULT now()
);
CREATE INDEX ON user_membership (user_id);
CREATE INDEX ON user_membership (plan_id);

CREATE TABLE bookings (
    booking_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code     varchar(20) NOT NULL UNIQUE,
    user_id          integer NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    first_name       varchar(100),
    last_name        varchar(100),
    phone            varchar(20),
    email            varchar(100),
    court_id         integer NOT NULL REFERENCES courts (court_id),
    slot_id          integer NOT NULL REFERENCES time_slots (slot_id),
    booking_date     date NOT NULL,
    duration_minutes integer NOT NULL,
    court_price      numeric(10,2) NOT NULL,
    equipment_total  numeric(10,2) DEFAULT 0,
    discount_amount  numeric(10,2) DEFAULT 0,
    discount_note    varchar(255),
    points_redeemed  integer NOT NULL DEFAULT 0,
    total_price      numeric(10,2) NOT NULL,
    payment_method   varchar(20) DEFAULT 'promptpay' CHECK (payment_method IN ('promptpay', 'bank_transfer')),
    payment_status   varchar(20) NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending', 'paid', 'failed', 'refunded')),
    expires_at       timestamp(0),
    booking_status   varchar(20) NOT NULL DEFAULT 'active' CHECK (booking_status IN ('active', 'cancelled', 'completed')),
    notes            text,
    created_at       timestamp(0) NOT NULL DEFAULT now(),
    updated_at       timestamp(0) NOT NULL DEFAULT now()
);
CREATE INDEX ON bookings (user_id);
CREATE INDEX ON bookings (court_id, booking_date);
CREATE INDEX ON bookings (slot_id);
CREATE TRIGGER bookings_updated_at BEFORE UPDATE ON bookings FOR EACH ROW EXECUTE FUNCTION hitthecourt.set_updated_at();

CREATE TABLE booking_slots (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id integer NOT NULL REFERENCES bookings (booking_id) ON DELETE CASCADE,
    slot_id    integer NOT NULL REFERENCES time_slots (slot_id),
    UNIQUE (booking_id, slot_id)
);
CREATE INDEX ON booking_slots (slot_id);

CREATE TABLE booking_equipment (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    integer NOT NULL REFERENCES bookings (booking_id) ON DELETE CASCADE,
    eq_id         integer NOT NULL REFERENCES equipment (eq_id),
    quantity      integer NOT NULL DEFAULT 1,
    free_quantity integer NOT NULL DEFAULT 0,
    unit_price    numeric(10,2) NOT NULL,
    subtotal      numeric(10,2) NOT NULL
);
CREATE INDEX ON booking_equipment (booking_id);
CREATE INDEX ON booking_equipment (eq_id);

CREATE TABLE payments (
    payment_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     integer NOT NULL REFERENCES bookings (booking_id) ON DELETE CASCADE,
    payment_method varchar(20) DEFAULT 'promptpay' CHECK (payment_method IN ('bank_transfer', 'promptpay', 'cash')),
    amount         numeric(10,2) NOT NULL,
    slip_image     varchar(255),
    reference_code varchar(100),
    payment_status varchar(20) NOT NULL DEFAULT 'pending' CHECK (payment_status IN ('pending', 'verified', 'rejected')),
    verified_by    integer,
    verified_at    timestamp(0),
    created_at     timestamp(0) NOT NULL DEFAULT now()
);
CREATE INDEX ON payments (booking_id);

CREATE TABLE reports (
    report_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_code varchar(20) NOT NULL UNIQUE,
    user_id     integer NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    category    varchar(20) NOT NULL DEFAULT 'other' CHECK (category IN ('cancel', 'damage', 'service', 'other')),
    topic       varchar(100) NOT NULL,
    description text NOT NULL,
    image_path  varchar(255),
    status      varchar(20) NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'in_progress', 'resolved')),
    admin_notes text,
    resolved_by integer,
    resolved_at timestamp(0),
    created_at  timestamp(0) NOT NULL DEFAULT now(),
    updated_at  timestamp(0) NOT NULL DEFAULT now()
);
CREATE INDEX ON reports (user_id);
CREATE TRIGGER reports_updated_at BEFORE UPDATE ON reports FOR EACH ROW EXECUTE FUNCTION hitthecourt.set_updated_at();

CREATE TABLE settings (
    setting_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key   varchar(100) NOT NULL UNIQUE,
    setting_value text,
    description   varchar(255),
    updated_at    timestamp(0) NOT NULL DEFAULT now()
);
CREATE TRIGGER settings_updated_at BEFORE UPDATE ON settings FOR EACH ROW EXECUTE FUNCTION hitthecourt.set_updated_at();

-- Session การล็อกอิน (SESSION_DRIVER=database)
CREATE TABLE sessions (
    id            varchar(128) PRIMARY KEY,
    data          text    NOT NULL,
    last_activity integer NOT NULL
);
CREATE INDEX ON sessions (last_activity);

-- ไฟล์อัปโหลด (UPLOAD_DRIVER=database) เก็บเป็น base64
CREATE TABLE uploaded_files (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folder     varchar(50)  NOT NULL,
    filename   varchar(255) NOT NULL,
    mime_type  varchar(100) NOT NULL,
    data       text         NOT NULL,
    created_at timestamp(0) NOT NULL DEFAULT now()
);

-- ---------- ความปลอดภัย ----------
-- เว็บเชื่อมต่อตรงด้วยรหัสผ่านฐานข้อมูล (ไม่ผ่าน REST API ของ Supabase)
-- เปิด RLS ทุกตารางโดยไม่มี policy และไม่ให้สิทธิ์ anon / authenticated
-- เพื่อไม่ให้ใครที่ถือ anon key อ่านหรือแก้ข้อมูลผ่าน API ได้
DO $$
DECLARE t text;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'hitthecourt' LOOP
        EXECUTE format('ALTER TABLE hitthecourt.%I ENABLE ROW LEVEL SECURITY', t);
    END LOOP;
END $$;
REVOKE ALL ON SCHEMA hitthecourt FROM anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA hitthecourt FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA hitthecourt FROM anon, authenticated;
REVOKE EXECUTE ON FUNCTION hitthecourt.set_updated_at() FROM PUBLIC, anon, authenticated;

-- ---------- บัญชีฐานข้อมูลสำหรับเว็บ ----------
-- เว็บใช้ role "hitthecourt_app" ที่เข้าถึงได้เฉพาะ schema นี้ (ไม่ต้องใช้รหัส postgres ของทั้งโปรเจกต์)
-- ตั้งรหัสผ่านแยกต่างหาก (ไม่เก็บในไฟล์นี้):
--   ALTER ROLE hitthecourt_app WITH LOGIN PASSWORD '...';
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hitthecourt_app') THEN
        CREATE ROLE hitthecourt_app NOLOGIN;
    END IF;
END $$;
ALTER ROLE hitthecourt_app SET search_path TO hitthecourt, public;
ALTER ROLE hitthecourt_app SET timezone TO 'Asia/Bangkok';
GRANT USAGE ON SCHEMA hitthecourt TO hitthecourt_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA hitthecourt TO hitthecourt_app;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA hitthecourt TO hitthecourt_app;
GRANT EXECUTE ON FUNCTION hitthecourt.set_updated_at() TO hitthecourt_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA hitthecourt GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO hitthecourt_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA hitthecourt GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO hitthecourt_app;

-- RLS เปิดอยู่ทุกตาราง: อนุญาตเฉพาะ role ของเว็บ (anon / authenticated ยังเข้าไม่ได้)
DO $$
DECLARE t text;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'hitthecourt' LOOP
        EXECUTE format('DROP POLICY IF EXISTS app_full_access ON hitthecourt.%I', t);
        EXECUTE format('CREATE POLICY app_full_access ON hitthecourt.%I FOR ALL TO hitthecourt_app USING (true) WITH CHECK (true)', t);
    END LOOP;
END $$;
