-- ============================================================
-- database/postgres/schema.sql
-- โครงสร้างฐานข้อมูล Hit The Court สำหรับ PostgreSQL (Supabase)
-- ทุกตารางอยู่ใน schema "hitthecourt" (แยกจากตารางอื่นในโปรเจกต์เดียวกัน)
-- เทียบเท่ากับ dump MySQL + database/vercel_tables.sql + migrations/001_spec_update.sql
